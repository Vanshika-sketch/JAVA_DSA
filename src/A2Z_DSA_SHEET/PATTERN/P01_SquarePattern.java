package A2Z_DSA_SHEET.PATTERN;

public class P01_SquarePattern {
    public static void main(String[] args) {
        int n = 5;
        for (int i = 0; i < n; i++) {
            for (int j = 0; j < n; j++) {
                System.out.print("*");

            }
            System.out.println();

        }


    }
}
